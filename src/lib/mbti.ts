export type Answers = Record<string, number>;

export type Result = {
  code: string;
  letters: Letter[];
  percentages: Record<AxisKey, number>;
};

export function computeResult(answers: Answers): Result {
  const totals: Record<AxisKey, { left: number; right: number }> = {
    EI: { left: 0, right: 0 },
    SN: { left: 0, right: 0 },
    TF: { left: 0, right: 0 },
    JP: { left: 0, right: 0 },
  };

  const count: Record<AxisKey, number> = { EI: 0, SN: 0, TF: 0, JP: 0 };

  for (const q of QUESTIONS) {
    const raw = answers[q.id];
    const v = typeof raw === "number" ? Math.max(-2, Math.min(2, raw)) : 0;
    const towardPole = (v + 2) / 4;
    const other = 1 - towardPole;
    const axis = AXES.find((a) => a.key === q.axis)!;
    if (q.pole === axis.left) {
      totals[q.axis].left += towardPole;
      totals[q.axis].right += other;
    } else {
      totals[q.axis].right += towardPole;
      totals[q.axis].left += other;
    }
    count[q.axis] += 1;
  }

  const letters: Letter[] = [];
  const percentages = {} as Record<AxisKey, number>;

  for (const axis of AXES) {
    const t = totals[axis.key];
    const rightPct = Math.round((t.right / count[axis.key]) * 100);
    percentages[axis.key] = Math.min(100, Math.max(0, rightPct));
    letters.push(rightPct >= 50 ? axis.right : axis.left);
  }

  return { code: letters.join(""), letters: letters as Letter[], percentages };
}

const MATCH = (code: string, note: string) => {
  const t = TYPES[code];
  return { code, ko: t ? t.ko : code, note };
};

